// ============================================================
// GameExitWatcher.cs —— "osu 退出了 → 该不该退出本程序"的状态机
//
// 【它解决什么问题】
//   打完歌关掉游戏之后，还留着一个悬浮窗和配置界面是多余的。
//   设置里「osu 退出时退出本程序」就是让软件自己收摊（★ 2026-09-23 用户提出）。
//
// 【★ 这个状态机存在的唯一理由：区分"退出了"和"从来就没在跑"】
//   光看"osu 现在不在运行"是不行的 —— 程序刚启动、用户还没开游戏的时候，
//   osu 本来就不在运行。把那种情况当成"刚退出"，**程序一启动就会自己关掉**。
//   所以必须先**见过它跑**，之后看不到它才算"退出"：
//
//     见过吗？  现在在跑吗？   结论
//     ────────  ────────────  ────────────────────────────
//       没有        没有       什么都不做（还没开过游戏）
//       没有        在跑       记下"见过"，什么都不做
//       见过        在跑       什么都不做
//       见过        没有       **触发一次**，并清掉"见过"
//
//   最后一行清掉"见过"是为了**只触发一次** —— 否则在程序真正退掉之前，
//   每轮检查都会喊一次"要退出"。
//
// 【为什么独立成文件】（《项目结构约定》§二、§三）
//   它是纯判断：喂一个 bool、返回一个 bool，没有 IO、没有 WPF ——
//   所以它能在控制台里被穷举测（见 `.build-verify/TosuSourceCheck` 第 ⑨ 节）。
//   "谁每 2 秒去问一次进程在不在"那件事属于 WPF 层（DispatcherTimer），不在这里。
// ============================================================
namespace OsuLive2dOverlay;

/// <summary>
/// 观察"osu 在不在跑"，回答"是不是刚刚退出了"。
/// **有状态**：它记着"这次运行期间见过 osu 没有"。
/// </summary>
public sealed class GameExitWatcher
{
    /// <summary>本次程序运行期间见过 osu 在跑没有</summary>
    private bool _seenRunning;

    /// <summary>见过 osu 在跑吗（给日志用）</summary>
    public bool HasSeenRunning => _seenRunning;

    /// <summary>
    /// 喂一次"osu 现在在不在跑"。
    /// 返回 <c>true</c> = **它刚刚退出了**（调用方该走了）。
    /// 同一次退出只会返回一次 true。
    /// </summary>
    public bool Observe(bool isRunning)
    {
        if (isRunning)
        {
            _seenRunning = true;
            return false;
        }

        if (!_seenRunning) return false;      // 从来没见过 → 不是"退出"，是"还没开"

        _seenRunning = false;                 // 清掉 → 防止同一次退出被反复报告
        return true;
    }

    /// <summary>
    /// 把状态清干净（开关被关掉时调）。
    ///
    /// 为什么重要：用户把开关关掉、过一会儿又打开时，
    /// 如果"见过"还留着，那么"现在没在跑"会被当成一次退出 —— 程序当场关掉。
    /// 关掉开关就等于**重新开始观察**。
    /// </summary>
    public void Reset() => _seenRunning = false;
}
