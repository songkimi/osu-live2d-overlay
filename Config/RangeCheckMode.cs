// ============================================================
// RangeCheckMode.cs —— 体检的"严格 / 宽松"（**独立成一个文件**）
//
// 【它为什么要独立】
//   这个枚举被**两边**用到，所以挂在哪一边都会让另一边多一个依赖：
//     · `ConfigHealthCheck.Check(config, env, mode)` —— 体检本身要用
//     · `HealthCheckConfig.Mode`                    —— 它是配置里的一项（`体检.检查模式`）
//
//   2026-09-20 ：先把它放进 `PluginConfig.cs`、后放进 `AppSettings.cs`，
//   两次都让"只链接体检文件"的验证工程编译不过 ——
//   因为那两个文件里没有它。
//   → 被两边共用的类型，**独立成文件**，谁需要谁就链接这一个文件。
//
// 语义（定稿 §3.4）：它**只作用在体检清单第 7~10 条**（区间与标识那一类），
// 名字本来就叫"区间检查"。其余条目大多也能兜住，但级别固定、不随模式变 ——
// 否则用户会以为"调一下模式就能让所有问题消失"。
// ============================================================
namespace OsuLive2dOverlay;

public enum RangeCheckMode
{
    /// <summary>宽松：兜住了就只提醒（Warning，可以点忽略放行）</summary>
    Lenient,

    /// <summary>严格：不给含糊（升级成 Error，必须改）</summary>
    Strict
}
